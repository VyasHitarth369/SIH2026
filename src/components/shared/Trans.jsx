export function translateText(text, lang) {
  if (lang !== 'hi' || text == null) return text;
  if (typeof text !== 'string') return text;

  const trimmed = text.trim();
  if (englishToHindi[trimmed]) return englishToHindi[trimmed];
  if (englishToHindi[text]) return englishToHindi[text];

  // Dynamic pattern matches
  if (text.startsWith('Allocated to ')) {
    const target = text.slice('Allocated to '.length);
    return `${englishToHindi[target] || target} को आवंटित किया गया`;
  }
  if (text.startsWith('Your Priority Rank: #')) {
    return `आपकी प्राथमिकता रैंक: #${text.slice('Your Priority Rank: #'.length)}`;
  }
  if (text.includes('You Accepted This Problem')) {
    return 'आपने इस समस्या को स्वीकार किया';
  }
  if (text.includes('You Rejected This Problem')) {
    return 'आपने इस समस्या को अस्वीकार किया';
  }
  if (text.startsWith('Students Working: ')) {
    return `कार्यरत छात्र: ${text.slice('Students Working: '.length)}`;
  }
  if (text.startsWith('Interested Applicants (')) {
    const num = text.replace(/[^\d]/g, '');
    return `इच्छुक आवेदक (${num})`;
  }
  if (text.endsWith(' students')) {
    const num = text.replace(/[^\d]/g, '');
    return `${num} छात्र`;
  }
  if (text.startsWith('Total Submitted: ')) {
    return `कुल प्रस्तुत: ${text.slice('Total Submitted: '.length)}`;
  }
  if (text.startsWith('Proposal ') && text.endsWith('.')) {
    const action = text.slice('Proposal '.length, -1).toLowerCase();
    return action === 'accepted' ? 'प्रस्ताव स्वीकार कर लिया गया।' : 'प्रस्ताव अस्वीकार कर दिया गया।';
  }
  if (text.startsWith('This problem is selected by ') && text.includes('so you would not have to work on this')) {
    const uni = text.replace('This problem is selected by ', '').replace(/\.?\s*so you would not have to work on this\.?/i, '').trim();
    return `यह समस्या ${englishToHindi[uni] || uni} द्वारा चुनी गई है इसलिए आपको इस पर काम नहीं करना होगा।`;
  }
  if (text.includes('days remaining') || text.includes('day remaining')) {
    return text
      .replace(/(\d+)\s*days?\s*remaining/gi, '$1 दिन शेष')
      .replace(/(\d+)d\s*(\d+)h\s*remaining/gi, '$1 दिन $2 घंटे शेष')
      .replace(/(\d+)h\s*(\d+)m\s*remaining/gi, '$1 घंटे $2 मिनट शेष')
      .replace('for accepting/rejecting', 'स्वीकार/अस्वीकार करने के लिए');
  }

  return text;
}

export function useTranslate() {
  const { lang } = useLanguage();
  return (text) => translateText(text, lang);
}

export default function Trans({ text }) {
  const { lang } = useLanguage();
  return translateText(text, lang);
}
